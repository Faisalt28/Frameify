export function getFilteredPool(query = '', categoryId = 'all') {
  let list = [...CURATED_POOL];
  const q = query.toLowerCase().trim();

  // Jika ada kategori tertentu (bukan 'all' dan bukan kosong)
  if (categoryId && categoryId !== 'all') {
    const filteredByCat = list.filter(item => item.tags?.includes(categoryId));
    if (filteredByCat.length > 0) {
      list = filteredByCat;
    }
  }

  // Jika ada teks pencarian
  if (q) {
    const filteredBySearch = list.filter(item =>
      item.alt_description?.toLowerCase().includes(q) ||
      item.tags?.some(t => t.toLowerCase().includes(q))
    );
    if (filteredBySearch.length > 0) {
      list = filteredBySearch;
    }
  }

  // Jika tanpa filter kategori ('all') dan tanpa search, acak urutan foto agar selalu bervariasi
  if ((!categoryId || categoryId === 'all') && !q) {
    return [...list].sort(() => Math.random() - 0.5);
  }

  return list;
}
